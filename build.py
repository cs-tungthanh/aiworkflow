#!/usr/bin/env python3
"""Build the skill set for Claude Code, Codex and Cursor, and install it.

  ./build.py build       generate dist/
  ./build.py install     build, then copy into ~/.claude, ~/.agents, ~/.codex, ~/.cursor
  ./build.py uninstall   remove what install put there
  add --dry-run to install/uninstall to print actions only
"""
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DIST = ROOT / "dist"
HOME = Path.home()
MARKER = "generated by ai-workflow"

# Rules copied into every skill's references/ (what an orchestrator reads).
SKILL_REFERENCES = ["rules/gather.md", "rules/delegate.md", "rules/responses.md"]

# Claude Code tools for a persona: read, search, shell for git/grep, and Write for its one output file.
# A persona's own `tools:` frontmatter replaces this (e.g. to add MCP tools).
CLAUDE_TOOLS = "Read, Grep, Glob, Bash, Write"

INCLUDE = re.compile(r"^\{\{include (\S+)\}\}$", re.M)

# Replaced in SKILL.md with this checkout's absolute path, so a skill can name files in the repo (mcp/ servers).
ROOT_PLACEHOLDER = "{{ai_workflow_root}}"


def parse_frontmatter(text):
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not m:
        raise ValueError("missing frontmatter")
    meta = {}
    for line in m.group(1).splitlines():
        key, _, value = line.partition(":")
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        meta[key.strip()] = value
    return meta, m.group(2).lstrip("\n")


def expand_includes(body):
    """Inline {{include rules/x.md}}, demoting its headings two levels to sit under a ## section."""
    def repl(m):
        included = (ROOT / m.group(1)).read_text().strip()
        return re.sub(r"^(#+) ", lambda h: "#" * min(len(h.group(1)) + 2, 6) + " ", included, flags=re.M)
    return INCLUDE.sub(repl, body)


def load_personas():
    personas = []
    for path in sorted((ROOT / "personas").glob("*.md")):
        meta, body = parse_frontmatter(path.read_text())
        personas.append((meta, expand_includes(body).rstrip() + "\n"))
    return personas


def toml_multiline(text):
    if "'''" not in text:
        return "'''\n" + text + "'''"
    escaped = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    return '"""\n' + escaped + '"""'


def yaml_quote(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build():
    if DIST.exists():
        shutil.rmtree(DIST)
    personas = load_personas()

    for meta, body in personas:
        name, desc = meta["name"], meta["description"]
        claude = DIST / "claude/agents" / f"{name}.md"
        claude.parent.mkdir(parents=True, exist_ok=True)
        claude.write_text(
            f"---\nname: {name}\ndescription: {yaml_quote(desc)}\ntools: {meta.get('tools', CLAUDE_TOOLS)}\n---\n\n<!-- {MARKER} -->\n\n{body}"
        )
        cursor = DIST / "cursor/agents" / f"{name}.md"
        cursor.parent.mkdir(parents=True, exist_ok=True)
        cursor.write_text(
            f"---\nname: {name}\ndescription: {yaml_quote(desc)}\nmodel: inherit\nreadonly: true\n---\n\n<!-- {MARKER} -->\n\n{body}"
        )
        codex = DIST / "codex/agents" / f"{name}.toml"
        codex.parent.mkdir(parents=True, exist_ok=True)
        codex.write_text(
            f"# {MARKER}\nname = {yaml_quote(name)}\ndescription = {yaml_quote(desc)}\n"
            f"developer_instructions = {toml_multiline(body)}\n"
        )

    for skill_dir in sorted((ROOT / "skills").iterdir()):
        if not (skill_dir / "SKILL.md").exists():
            continue
        out = DIST / "skills" / skill_dir.name
        shutil.copytree(skill_dir, out)
        skill_text = (skill_dir / "SKILL.md").read_text()
        (out / "SKILL.md").write_text(skill_text.replace(ROOT_PLACEHOLDER, str(ROOT)))
        meta, skill_body = parse_frontmatter(skill_text)
        if meta.get("name") != skill_dir.name:
            raise ValueError(f"{skill_dir.name}: frontmatter name must match folder name")
        # The shared rules go to skills that point at references/; a persona goes to every skill that
        # names it, in its own text or in those rules (the fallback when the persona is not installed).
        reads = skill_body
        if "references/" in skill_body:
            (out / "references").mkdir(exist_ok=True)
            for ref in SKILL_REFERENCES:
                shutil.copy(ROOT / ref, out / "references" / Path(ref).name)
                reads += (ROOT / ref).read_text()
        for pmeta, body in personas:
            if pmeta["name"] in reads:
                (out / "personas").mkdir(exist_ok=True)
                (out / "personas" / f"{pmeta['name']}.md").write_text(body)
        implicit = "false" if meta.get("disable-model-invocation") == "true" else "true"
        title = " ".join({"pr": "PR", "chatgpt": "ChatGPT"}.get(w, w.capitalize()) for w in skill_dir.name.split("-"))
        (out / "agents").mkdir(exist_ok=True)
        (out / "agents/openai.yaml").write_text(
            f"interface:\n  display_name: {yaml_quote(title)}\n  short_description: {yaml_quote(meta['description'])}\n"
            f"policy:\n  allow_implicit_invocation: {implicit}\n"
        )
        (out / ".ai-workflow").write_text(MARKER + "\n")

    print(f"built {len(personas)} personas, {len(list((DIST / 'skills').iterdir()))} skills into {DIST}")


def targets():
    """(source in dist, destination) pairs for every installed item."""
    pairs = []
    for skill in sorted((DIST / "skills").iterdir()):
        for root in (HOME / ".claude/skills", HOME / ".agents/skills"):
            pairs.append((skill, root / skill.name))
    for tool, home_dir in (("claude", ".claude/agents"), ("cursor", ".cursor/agents"), ("codex", ".codex/agents")):
        for f in sorted((DIST / tool / "agents").iterdir()):
            pairs.append((f, HOME / home_dir / f.name))
    return pairs


def owned(dest):
    if dest.is_dir():
        return (dest / ".ai-workflow").exists()
    return MARKER in dest.read_text(errors="ignore")


def install(dry_run):
    build()
    for src, dest in targets():
        if dest.exists() and not owned(dest):
            sys.exit(f"refusing to overwrite {dest}: not created by ai-workflow")
    for src, dest in targets():
        print(f"install {dest}")
        if dry_run:
            continue
        if dest.is_dir():
            shutil.rmtree(dest)
        dest.parent.mkdir(parents=True, exist_ok=True)
        if src.is_dir():
            shutil.copytree(src, dest)
        else:
            shutil.copy(src, dest)


def uninstall(dry_run):
    build()
    for _, dest in targets():
        if dest.exists() and owned(dest):
            print(f"remove {dest}")
            if not dry_run:
                shutil.rmtree(dest) if dest.is_dir() else dest.unlink()


if __name__ == "__main__":
    args = sys.argv[1:]
    dry = "--dry-run" in args
    cmd = next((a for a in args if not a.startswith("--")), "build")
    {"build": lambda: build(), "install": lambda: install(dry), "uninstall": lambda: uninstall(dry)}.get(
        cmd, lambda: sys.exit(__doc__)
    )()
